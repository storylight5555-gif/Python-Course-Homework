import math
print("The floor and ceiling of 3.7 are:", math.floor(3.7), "and", math.ceil(3.7))
print("copysign of -5 and 3 is:", math.copysign(-5, 3))
print("The absolute value of -5 is:", math.fabs(-5))
print("The square root of 16 is:", math.sqrt(16))
print("The factorial of 5 is:", math.factorial(5))
print("The greatest common divisor of 48 and 18 is:", math.gcd(48, 18))
